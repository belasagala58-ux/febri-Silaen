export function getQuestionsByGrade(grade: GradeLevel): Question[] {
  return QUESTION_DATABASE.filter((q) => q.grade === grade);
}

export function getRandomQuestions(grade: GradeLevel, count: number = 8): Question[] {
  const pool = getQuestionsByGrade(grade);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
